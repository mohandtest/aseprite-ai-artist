return function(check, withMockSprite, call, eq)
  local function rejected(cmd,args,code)
    local reply=_G.AI_ARTIST.handleCommand({id="guard",cmd=cmd,args=args})
    assert(not reply.ok,"Expected rejection")
    eq(reply.error.code,code,"rejection code")
  end
  local function draw(s,extra)
    local args={sprite="#"..s.id,layer=s.layers[1].name,frame=1,paletteLock=false,
      ops={{kind="pixels",color="#ff0000",points={{x=2,y=3}}}}}
    for k,v in pairs(extra or {}) do args[k]=v end
    return call("draw.batch",args)
  end
  local function read(s,region)
    return call("pixels.read",{sprite="#"..s.id,layer=s.layers[1].name,frame=1,composite=false,region=region})
  end
  check("preview does not mutate pixels or leave active site changed",function()
    withMockSprite(8,8,nil,function(s)
      local before=read(s);local layer=app.layer;local frame=app.frame
      local result=draw(s,{mode="preview"})
      eq(result.pixelsChanged,1,"unique diff count");assert(result.preview and not result.applied)
      eq(read(s).fingerprint,before.fingerprint,"preview token")
      assert(app.sprite==s and app.layer==layer and app.frame==frame,"preview altered site")
    end)
  end)
  check("preview and apply use identical raster output",function()
    withMockSprite(8,8,nil,function(s)
      local a=draw(s,{mode="preview"});local b=draw(s)
      eq(a.pixelsChanged,b.pixelsChanged,"parity count");eq(a.bounds.x,b.bounds.x,"parity bounds")
      local action=call("look.action_diff",{sprite="#"..s.id,actionId=b.actionId})
      eq(action.changes[1].after,a.changes[1].after,"parity color")
      eq(action.pixelsChanged,1,"action count")
    end)
  end)
  check("overlapping writes count unique final changes, noops don't add actions",function()
    withMockSprite(8,8,nil,function(s)
      local args={ops={{kind="pixels",color="#ff0000",points={{x=2,y=3},{x=2,y=3}}}}}
      eq(draw(s,args).pixelsChanged,1,"dedup count");eq(draw(s,args).pixelsChanged,0,"no-op")
    end)
  end)
  check("stale fingerprints reject without changes",function()
    withMockSprite(8,8,nil,function(s)
      local before=read(s);draw(s)
      local after=read(s)
      rejected("draw.batch",{sprite="#"..s.id,layer=s.layers[1].name,guard={expectedRegionFingerprint=before.fingerprint},ops={{kind="clear"}}},"stale_region")
      eq(read(s).fingerprint,after.fingerprint,"rejected stale edit")
    end)
  end)
  check("palette changes invalidate pixel fingerprints",function()
    withMockSprite(8,8,nil,function(s)
      local a=read(s).fingerprint
      app.transaction(function() local pal=s.palettes[1];pal:setColor(1,Color{r=12,g=34,b=56});s:setPalette(pal) end)
      assert(a~=read(s).fingerprint,"palette not fingerprinted")
    end)
  end)
  check("allowedRegion checks actual diff, not declared op bounds",function()
    withMockSprite(8,8,nil,function(s)
      local before=read(s).fingerprint
      rejected("draw.batch",{sprite="#"..s.id,paletteLock=false,guard={allowedRegion={x=0,y=0,width=1,height=1}},ops={{kind="fill",at={x=0,y=0},color="#ffffff"}}},"protected_region_changed")
      eq(read(s).fingerprint,before,"protected edit")
    end)
  end)
  check("change budgets reject before creating missing cels",function()
    withMockSprite(8,8,nil,function(s)
      app.transaction(function() s:deleteCel(s.layers[1]:cel(1)) end)
      rejected("draw.batch",{sprite="#"..s.id,paletteLock=false,guard={maxChangedPixels=0},ops={{kind="pixels",color="#ffffff",points={{x=1,y=1}}}}},"change_budget_exceeded")
      assert(not s.layers[1]:cel(1),"Rejected edit created a cel")
    end)
  end)
  check("sparse patch preconditions are exact and atomic",function()
    withMockSprite(8,8,nil,function(s)
      draw(s,{ops={{kind="grid_patch",points={{x=1,y=1,expectedColor="#00000000",newColor="#ffffff"}}}}})
      local a=read(s).fingerprint
      rejected("draw.batch",{sprite="#"..s.id,paletteLock=false,ops={{kind="grid_patch",points={{x=2,y=2,expectedColor="#00000000",newColor="#ffffff"},{x=1,y=1,expectedColor="#00000000",newColor="#ff0000"}}}}},"stale_region")
      eq(read(s).fingerprint,a,"partial patch mutation")
    end)
  end)
  check("invalid draw operation cannot partially mutate original",function()
    withMockSprite(8,8,nil,function(s)
      local a=read(s).fingerprint
      rejected("draw.batch",{sprite="#"..s.id,paletteLock=false,ops={{kind="pixels",color="#ffffff",points={{x=1,y=1}}},{kind="pretend"}}},"unsupported_command")
      eq(read(s).fingerprint,a,"partial batch mutation")
    end)
  end)
  check("cropped fingerprint guard matches exact region",function()
    withMockSprite(8,8,nil,function(s)
      local region={x=2,y=3,width=2,height=2};local a=read(s,region)
      draw(s,{guard={expectedRegionFingerprint=a.fingerprint,fingerprintRegion=region,allowedRegion=region}})
    end)
  end)
  check("PixelSpec is shared by document ID and enforced on draw",function()
    withMockSprite(8,8,nil,function(s)
      call("spec.set",{sprite="#"..s.id,spec={schemaVersion=1,protectedRegions={{layer=s.layers[1].name,region={x=2,y=3,width=1,height=1}}}}})
      assert(call("spec.get",{sprite="#"..s.id}).spec,"Spec lost across lookup")
      rejected("draw.batch",{sprite="#"..s.id,paletteLock=false,ops={{kind="pixels",color="#ff0000",points={{x=2,y=3}}}}},"spec_constraint_failed")
      eq(read(s).grid[27],0,"protected pixel")
    end)
  end)
  check("PixelSpec canvas mismatch is reported",function()
    withMockSprite(8,8,nil,function(s)
      call("spec.set",{sprite="#"..s.id,spec={schemaVersion=1,hard={canvasSize={16,16}}}})
      eq(#call("spec.validate",{sprite="#"..s.id}).issues,1,"canvas mismatch")
    end)
  end)
  check("action cache is bounded and refuses wrong document",function()
    withMockSprite(8,8,nil,function(s)
      local result=draw(s)
      withMockSprite(8,8,nil,function(other)
        rejected("look.action_diff",{sprite="#"..other.id,actionId=result.actionId},"action_not_found")
      end)
    end)
  end)
  check("scale tween requires explicit lossy opt-in",function()
    withMockSprite(8,8,nil,function(s)
      call("frame.apply",{sprite="#"..s.id,op="add",count=1})
      rejected("cel.apply",{sprite="#"..s.id,op="tween",property="scale",fromFrame=1,toFrame=2,to=2},"invalid_args")
    end)
  end)
  check("preview and rejected edits add no undo while successful batch adds one",function()
    withMockSprite(8,8,nil,function(s)
      local empty=read(s).fingerprint
      draw(s)
      draw(s,{mode="preview",ops={{kind="pixels",color="#ffffff",points={{x=1,y=1}}}}})
      rejected("draw.batch",{sprite="#"..s.id,paletteLock=false,guard={maxChangedPixels=0},ops={{kind="pixels",color="#ffffff",points={{x=1,y=1}}}}},"change_budget_exceeded")
      app.command.Undo()
      eq(read(s).fingerprint,empty,"preview/rejection inserted undo")
      draw(s,{ops={{kind="pixels",color="#ffffff",points={{x=1,y=1}}},{kind="pixels",color="#ff0000",points={{x=2,y=2}}}}})
      app.command.Undo()
      eq(read(s).fingerprint,empty,"batch required more than one undo")
    end)
  end)
  check("selection clips preview and commit without changing the selection",function()
    withMockSprite(8,8,nil,function(s)
      s.selection:select(Rectangle(2,3,1,1))
      local args={selectionOnly=true,ops={{kind="rect",color="#ff0000",fill="#ff0000",rect={x=0,y=0,width=8,height=8}}}}
      args.mode="preview";eq(draw(s,args).pixelsChanged,1,"preview selection")
      args.mode="apply";eq(draw(s,args).pixelsChanged,1,"commit selection")
      eq(s.selection.bounds.x,2,"selection x");eq(s.selection.bounds.width,1,"selection width")
    end)
  end)
  check("scale tween uses frozen source with fixed anchor",function()
    withMockSprite(16,16,nil,function(s)
      app.transaction(function()
        local image=Image(2,2,ColorMode.RGB);image:clear(app.pixelColor.rgba(255,0,0,255))
        s.cels[1].image=image;s.cels[1].position=Point(4,4)
      end)
      call("frame.apply",{sprite="#"..s.id,op="add",count=2})
      local result=call("cel.apply",{sprite="#"..s.id,layer=s.layers[1].name,op="tween",property="scale",fromFrame=1,toFrame=3,to=2,allowLossy=true,anchor={x=4,y=4}})
      eq(result.applied,3,"scale frames");eq(s.layers[1]:cel(3).image.width,4,"scale width")
      eq(s.layers[1]:cel(1).image.width,2,"source preserved");eq(s.layers[1]:cel(3).position.x,4,"fixed anchor")
    end)
  end)

  check("indexed reads and sparse erase honor nonzero transparent index",function()
    withMockSprite(8,8,ColorMode.INDEXED,function(s)
      app.transaction(function()
        s.transparentColor=7
        local pal=s.palettes[1];pal:setColor(1,Color{r=255,g=0,b=0});s:setPalette(pal)
        s.cels[1].image:clear(7)
      end)
      eq(read(s).grid[1],0,"nonzero transparent read")
      draw(s,{ops={{kind="grid_patch",points={{x=1,y=1,expectedColor="#00000000",newColor="#ff0000"}}}}})
      draw(s,{ops={{kind="grid_patch",points={{x=1,y=1,expectedColor="#ff0000",newColor="#00000000"}}}}})
      eq(read(s).grid[10],0,"indexed sparse erase")
    end)
  end)

end
